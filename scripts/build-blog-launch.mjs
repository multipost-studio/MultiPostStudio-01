// Bundles src/content/blog-launch/NN-slug.md into src/content/blog-launch/posts.generated.ts.
// Run: npm run blog:build   (exits non-zero if any post is malformed)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "content", "blog-launch");
const KEYS = ["title", "slug", "excerpt", "seoTitle", "seoDescription", "focusKeyword", "secondaryKeywords", "category", "tags", "readMins"];
const CATEGORIES = ["Platform Guides", "Scheduling & Workflow", "Strategy", "Analytics", "AI & Automation", "Agencies & Teams"];

const files = readdirSync(dir).filter((f) => /^\d{2}-.+\.md$/.test(f)).sort();
const posts = [];
const problems = [];
const seen = new Set();

for (const file of files) {
  const raw = readFileSync(join(dir, file), "utf8").replace(/\r\n?/g, "\n");
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(raw);
  if (!m) {
    problems.push(`${file}: missing frontmatter`);
    continue;
  }
  const fm = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) {
      let v = line.slice(i + 1).trim();
      // Values containing ": " are written in quotes; unwrap them.
      if (v.length > 1 && ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'")))) v = v.slice(1, -1).replace(/\\"/g, '"');
      fm[line.slice(0, i).trim()] = v;
    }
  }
  const missing = KEYS.filter((k) => !fm[k]);
  if (missing.length) problems.push(`${file}: missing ${missing.join(", ")}`);
  if (fm.category && !CATEGORIES.includes(fm.category)) problems.push(`${file}: unknown category "${fm.category}"`);
  if (fm.slug && seen.has(fm.slug)) problems.push(`${file}: duplicate slug ${fm.slug}`);
  seen.add(fm.slug);
  if (fm.slug && !file.endsWith(`${fm.slug}.md`)) problems.push(`${file}: file name does not match slug ${fm.slug}`);

  const content = m[2].trim();
  posts.push({
    order: Number(file.slice(0, 2)),
    slug: fm.slug,
    title: fm.title,
    excerpt: fm.excerpt,
    seoTitle: fm.seoTitle,
    seoDescription: fm.seoDescription,
    focusKeyword: fm.focusKeyword,
    secondaryKeywords: fm.secondaryKeywords,
    category: fm.category,
    tags: (fm.tags ?? "").split(",").map((t) => t.trim()).filter(Boolean),
    readMins: Math.max(1, Math.round(content.split(/\s+/).length / 200)),
    content,
  });
}

if (problems.length) {
  console.error("Blog launch build failed:\n - " + problems.join("\n - "));
  process.exit(1);
}

const out =
  "// GENERATED by scripts/build-blog-launch.mjs from src/content/blog-launch/*.md — do not edit by hand.\n" +
  'import type { LaunchPost } from "@/lib/blog-launch";\n\n' +
  "export const BLOG_LAUNCH_POSTS: LaunchPost[] = " +
  JSON.stringify(posts, null, 1) +
  ";\n";
writeFileSync(join(dir, "posts.generated.ts"), out);
console.log(`Wrote ${posts.length} posts (${posts.reduce((n, p) => n + p.content.split(/\s+/).length, 0).toLocaleString()} words).`);
